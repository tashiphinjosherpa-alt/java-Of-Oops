package july;

public class Multiplication_Table {
    public static void main(String[] args) {

        int num= 5;

        System.out.println(" Multiplication Table Of "+num+ ":");


        for (int i=1; i<=10;i++)
        {
int result = num * i;
System.out.println(num+" X "+i+ " = " +result);

        }




    }
}