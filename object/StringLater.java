public class StringLater {
    public static void main(String[] args) {
        
        String greeting="helo my name is tashi phinjo sherpa";
        System.out.println("string greeting is "+greeting);

        String empty=" ";
        System.out.println("String empty "+empty);

        String multiLineString= "Line1\nLine2";
        System.out.println("String multiline "+multiLineString);


        String quotedString="He said , \"Hello!\"";
        System.out.println("String with escape sequence "+quotedString);

        String tabbledString="Item1\tItem2";
        System.out.println("String with escape sequence "+tabbledString);
    }
}
