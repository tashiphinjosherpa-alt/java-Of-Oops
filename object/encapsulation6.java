class Teacher{

private String name;
private String education;
private String skill;
private int age;
private int salary;

Teacher(String name, String education, String skill, int age, int salary){
this.name=name;
this.education=education;
this.skill=skill;
this.age=age;
this.salary=salary;
}


public String getName(){

    return name;
}

public String getEducation(){

    return education;
}

public String getSkill(){

    return skill;
}

public int getAge(){

    return age;
}

public int getSalary(){

    return salary;
}

public String setName(String name){
    this.name=name;

    return name;
}

public String setEducation(String education){
    this.education= education;

    return education;
}

public String setSkill(String skill){
    this.skill=skill;

    return skill;
}

public int setAge(int age){
    this.age= age;

    return age;
}

public int setSalary(int salary){
    this.salary= salary;

    return salary;
}




}
