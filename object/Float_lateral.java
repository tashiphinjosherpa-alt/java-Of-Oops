public class Float_lateral {
  public static void main(String[] args) {
    
    float pi=3.14f;
    System.out.println("float lateral : "+pi);

    double e= 2.178;
    System.out.println("double lateral : "+e);

double largeNum=1.23e4;//equivalent to 1.2*10^4=12300
System.out.println("Scientific Notation(large num) : "+largeNum);



double smallNum=4.56e-3;
System.out.println("scientific notation(small num) : " +smallNum);


//precision with double
double preciseNum=3.1213141233;
System.out.println("Double with precision (preciseNum) : "+preciseNum);
  }  
}
